include!(concat!(env!("OUT_DIR"), "/templates_gen.rs"));

#[cfg(test)]
mod tests {
    use super::format_ars;

    #[test]
    fn format_ars_smoke() {
        for (price, expected) in [
            (328000.0, "328.000"),
            (4564.91, "4.564,91"),
            (3744.05, "3.744,05"),
            (95400.0, "95.400"),
            (500.0, "500"),
            (1234.56, "1.234,56"),
        ] {
            assert_eq!(format_ars(price), expected);
        }
    }
}
